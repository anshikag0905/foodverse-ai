/**
 * Fuzzy search helper covering English, Hindi, tags, and category terms
 */
export function searchPredefinedFoods(query) {
  if (!query || !query.trim()) return PREDEFINED_FOODS.slice(0, 30);
  const cleanQ = query.toLowerCase().trim();

  // Special aliases: e.g. "sabzi", "potato", "aloo", "banana", "kela"
  return PREDEFINED_FOODS.filter(item => {
    const nameMatch = item.name.toLowerCase().includes(cleanQ);
    const hiMatch = item.name_hi && item.name_hi.toLowerCase().includes(cleanQ);
    const catMatch = item.category.toLowerCase().includes(cleanQ);
    const cuiMatch = item.cuisine && item.cuisine.toLowerCase().includes(cleanQ);
    const tagMatch = item.gym_tags && item.gym_tags.some(tag => tag.includes(cleanQ));
    return nameMatch || hiMatch || catMatch || cuiMatch || tagMatch;
  });
}
